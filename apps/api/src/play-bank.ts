export async function initializePlay() {
  await GameDefinition.updateOne(
    { key: "this_or_that" },
    { $setOnInsert: { key: "this_or_that" } },
    { upsert: true },
  );
  await GameQuestion.bulkWrite(
    playCategories.flatMap((category) =>
      bank[category].map(([text, optionA, optionB], index) => ({
        updateOne: {
          filter: { key: `${category}-${index + 1}` },
          update: {
            $setOnInsert: {
              key: `${category}-${index + 1}`,
              category,
              text,
              optionA,
              optionB,
              active: true,
              tone: "playful",
            },
          },
          upsert: true,
        },
      })),
    ),
  );
}
